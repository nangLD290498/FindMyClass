CREATE TABLE app_users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_subject VARCHAR2(255 CHAR) NOT NULL,
    email VARCHAR2(320 CHAR) NOT NULL,
    display_name VARCHAR2(255 CHAR) NOT NULL,
    role VARCHAR2(16 CHAR),
    CONSTRAINT uq_users_google_subject UNIQUE (google_subject),
    CONSTRAINT ck_users_role CHECK (role IN ('TEACHER', 'STUDENT'))
);
CREATE TABLE teacher_profiles (
    user_id NUMBER(19) PRIMARY KEY,
    bio CLOB NOT NULL,
    subjects VARCHAR2(500 CHAR) NOT NULL,
    CONSTRAINT fk_teacher_user FOREIGN KEY (user_id) REFERENCES app_users(id)
);
